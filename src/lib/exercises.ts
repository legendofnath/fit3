import type { AvoidTag, Exercise, Kind, Movement, Muscle, Pattern, Tier } from "./types";

const PUSH_MUSCLES: Muscle[] = ["chest", "shoulders", "triceps", "quads", "calves"];

function movementFor(pattern: Pattern, muscle: Muscle): Movement {
  switch (pattern) {
    case "h_push":
    case "v_push":
      return "push";
    case "h_pull":
    case "v_pull":
      return "pull";
    case "squat":
    case "lunge":
      return "squat";
    case "hinge":
      return "hinge";
    case "core":
    case "carry":
      return "core";
    case "cardio":
      return "cardio";
    default:
      if (muscle === "glutes" || muscle === "hamstrings") return "hinge";
      return PUSH_MUSCLES.includes(muscle) ? "push" : "pull";
  }
}

function kindFor(pattern: Pattern): Kind {
  if (pattern === "cardio") return "cardio";
  if (pattern === "isolation" || pattern === "core") return "isolation";
  return "compound";
}

/**
 * One exercise row:
 * id, name, required equipment, primary muscle, secondary muscles, pattern,
 * tier, staple (1-3), fatigue (1-3), difficulty (1-3), rep range, avoid tags,
 * how-to cue, most common mistake.
 */
function x(
  id: string,
  name: string,
  requires: string[],
  muscle: Muscle,
  secondary: Muscle[],
  pattern: Pattern,
  tier: Tier,
  staple: 1 | 2 | 3,
  fatigue: 1 | 2 | 3,
  difficulty: 1 | 2 | 3,
  repRange: [number, number],
  avoid: AvoidTag[],
  cues: string,
  mistake: string,
): Exercise {
  return {
    id,
    name,
    requires,
    muscle,
    secondary,
    movement: movementFor(pattern, muscle),
    pattern,
    kind: kindFor(pattern),
    tier,
    staple,
    fatigue,
    difficulty,
    repRange,
    avoid,
    cues,
    mistake,
  };
}

